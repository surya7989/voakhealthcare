<?php

declare(strict_types=1);

/**
 * Voak Health Care — Super Administrator Provisioning CLI Command
 * Usage:
 *   php backend/cli/create_super_admin.php --email="admin@voak.health" --name="System Administrator" [--password="Secret123!@#"]
 */

namespace Voak\Health\CLI;

use Voak\Health\Auth\RbacManager;
use Voak\Health\Core\Config;
use Voak\Health\Database\Connection;
use Voak\Health\Security\AuditLogger;
use Voak\Health\Security\PasswordHasher;

$autoloadPaths = [
    __DIR__ . '/../vendor/autoload.php',
    __DIR__ . '/../../vendor/autoload.php',
];

$loaded = false;
foreach ($autoloadPaths as $path) {
    if (file_exists($path)) {
        require_once $path;
        $loaded = true;
        break;
    }
}

if (!$loaded) {
    fwrite(STDERR, "[ERROR] Composer autoloader not found. Run composer install.\n");
    exit(1);
}

ini_set('memory_limit', '512M');

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    echo "CLI execution only.\n";
    exit(1);
}

// Parse arguments
$options = getopt('', ['email:', 'name:', 'sqlite::', 'interactive', 'help']);

// Explicitly prohibit --password argument to prevent exposure in process tables and shell history
foreach ($argv as $arg) {
    if (str_starts_with($arg, '--password=') || $arg === '--password') {
        fwrite(STDERR, "[SECURITY ERROR] Passwords cannot be passed via command-line arguments as they are exposed in process listings (ps aux) and shell history.\n");
        fwrite(STDERR, "Please provide the password interactively, set the VOAK_ADMIN_PASSWORD environment variable, or omit it to auto-generate a secure credential.\n");
        exit(1);
    }
}

if (isset($options['help'])) {
    echo "Voak Health Care — Initial Super Admin CLI Provisioner\n";
    echo "Usage:\n";
    echo "  php " . basename(__FILE__) . " --email=\"admin@voak.health\" --name=\"Administrator\" [--interactive] [--sqlite[=path]]\n";
    echo "Environment:\n";
    echo "  VOAK_ADMIN_PASSWORD    Optional pre-set password for headless automated provisioning.\n";
    exit(0);
}

$email = $options['email'] ?? null;
$name = $options['name'] ?? null;
$sqlite = $options['sqlite'] ?? null;

if (!$email || !$name) {
    fwrite(STDERR, "[ERROR] Missing required arguments --email and --name.\n");
    echo "Example: php " . basename(__FILE__) . " --email=\"admin@voak.health\" --name=\"Lead Admin\"\n";
    exit(1);
}

// Bootstrap DB connection
if ($sqlite !== null || getenv('DB_DRIVER') === 'sqlite') {
    $path = is_string($sqlite) && $sqlite !== '' ? $sqlite : (getenv('DB_DATABASE') ?: ':memory:');
    $pdo = new \PDO("sqlite:{$path}", null, null, [
        \PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION,
        \PDO::ATTR_DEFAULT_FETCH_MODE => \PDO::FETCH_ASSOC,
    ]);
    $pdo->exec("PRAGMA foreign_keys = ON;");
} else {
    $envFile = __DIR__ . '/../.env';
    $config = file_exists($envFile) ? Config::fromEnvFile($envFile) : Config::fromGlobals();
    $connection = Connection::fromConfig($config);
    $pdo = $connection->getPdo();
}

// Resolve password securely
$password = getenv('VOAK_ADMIN_PASSWORD') ?: null;
if (!$password && (isset($options['interactive']) || (function_exists('posix_isatty') && posix_isatty(STDIN)))) {
    echo "Enter Super Admin password (min 12 chars) or press Enter to auto-generate: ";
    $line = fgets(STDIN);
    if ($line !== false && trim($line) !== '') {
        $password = trim($line);
    }
}

// Generate secure password if omitted
$autoGenerated = false;
if (!$password) {
    $autoGenerated = true;
    $password = 'VoakAdmin!' . bin2hex(random_bytes(4)) . '$7';
}

$hasher = new PasswordHasher();
$rbacManager = new RbacManager();
$auditLogger = new AuditLogger();

try {
    // 1. Validate entropy
    $hasher->enforceEntropy($password);

    // 2. Seed RBAC roles & permissions
    $rbacManager->seedRbac($pdo);

    // 3. Check existing user
    $stmt = $pdo->prepare("SELECT `id` FROM `users` WHERE `email` = :email");
    $stmt->execute(['email' => strtolower(trim($email))]);
    $existing = $stmt->fetchColumn();
    $stmt->closeCursor();

    if ($existing !== false) {
        fwrite(STDERR, "[WARNING] User with email [{$email}] already exists (ID: {$existing}). Assigning super_admin role...\n");
        $userId = (int)$existing;
        $rbacManager->assignRole($pdo, $userId, RbacManager::ROLE_SUPER_ADMIN);
    } else {
        $hash = $hasher->hash($password);
        $insert = $pdo->prepare(
            "INSERT INTO `users` (`name`, `email`, `password_hash`, `is_active`, `created_at`, `updated_at`) 
             VALUES (:name, :email, :hash, 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)"
        );
        $insert->execute([
            'name'  => trim($name),
            'email' => strtolower(trim($email)),
            'hash'  => $hash,
        ]);
        $userId = (int)$pdo->lastInsertId();
        $insert->closeCursor();

        $rbacManager->assignRole($pdo, $userId, RbacManager::ROLE_SUPER_ADMIN);
    }

    // 4. Record tamper-evident audit log
    $auditLogger->log(
        $pdo,
        'security',
        'ADMIN_BOOTSTRAP_PROVISIONED',
        $userId,
        '127.0.0.1',
        'CLI Provisioner',
        'user',
        $userId,
        ['email' => $email, 'role' => RbacManager::ROLE_SUPER_ADMIN]
    );

    echo "======================================================================\n";
    echo "SUCCESS: Super Administrator provisioned successfully!\n";
    echo "User ID:   {$userId}\n";
    echo "Name:      {$name}\n";
    echo "Email:     {$email}\n";
    echo "Role:      " . RbacManager::ROLE_SUPER_ADMIN . " (Unrestricted authority)\n";
    if ($autoGenerated) {
        echo "Password:  {$password}\n";
        echo "NOTE: Store this temporary password safely and rotate upon first login.\n";
    }
    echo "======================================================================\n";
    exit(0);
} catch (\Throwable $e) {
    fwrite(STDERR, "[ERROR] Provisioning failed: " . $e->getMessage() . "\n");
    exit(1);
}
